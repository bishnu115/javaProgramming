package Basic_java;

import java.util.Scanner;

public class EvenOrOdd {
    public static void main(String[] args) {

        int num = 57;
        if (num % 2 == 0) {
            System.out.println(num + " is Even.");
        } else {
            System.out.println(num + " is Odd.");
        }
    }
}

